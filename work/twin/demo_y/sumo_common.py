"""SUMO 侧两个共用件：可执行文件定位 + 抹掉产物头的生成时间戳。

**为什么要有 `strip_sumo_timestamp`**：SUMO 家族（`netconvert` / `sumo`）**每次都会**在产物
第一行写 `<!-- generated on <时间> by Eclipse SUMO ... -->`。于是"同一份输入重跑"必然产生
**一条毫无意义的时间戳 diff**，而仓库第 7 节的口径是「**重跑不许产生无意义 diff**」。

本函数只把那个时间抹掉，**不碰任何内容**（路网结构、车流、指标一字不动）。
要改产物，请改**输入或转换参数**后重跑脚本 —— 不许手改生成物。

用法（两个建脚本都 import 它）：
    from sumo_common import sumo_binary, strip_sumo_timestamp
"""

from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

#: SUMO 产物首行的生成时间戳注释
_GENERATED_ON = re.compile(r"<!-- generated on [^ ]+ by ")

#: `netconvert` 回显进 `.net.xml` 的选项块（**标签是 `<netconvertConfiguration>`**，
#: 里面是**本机绝对路径**；别跟 `sumocfg` 的 `<configuration>` 混了）
_CONFIGURATION_BLOCK = re.compile(
    r"\n[ \t]*<netconvertConfiguration\b.*?</netconvertConfiguration>[ \t]*\n", re.S
)


def sumo_binary(name: str) -> str:
    """定位 SUMO 的可执行文件：先看 `$SUMO_HOME/bin`，再看 PATH；都没有就给**可操作**的报错。

    **不在脚本里写死任何盘符或本机绝对路径** —— 换台机器只改环境变量，不改代码。
    """
    sumo_home = os.environ.get("SUMO_HOME")
    if sumo_home:
        candidate = Path(sumo_home) / "bin" / name
        if candidate.is_file():
            return str(candidate)
    found = shutil.which(name)
    if found:
        return found
    raise SystemExit(
        f"找不到 {name}。请先装 SUMO 并设好 SUMO_HOME：\n"
        f"  export SUMO_HOME=<SUMO 安装根目录>        # 该目录下应有 bin/ 与 tools/\n"
        f"  （也可以把 {name} 放进 PATH；两条都没有时不静默跳过）"
    )


def strip_sumo_timestamp(path: Path) -> bool:
    """抹掉产物首行的生成时间戳。改动了返回 True。

    只替换那一行注释里的时间；文件其余部分**原样保留**。
    """
    text = path.read_text(encoding="utf-8")
    stripped, count = _GENERATED_ON.subn("<!-- generated by ", text, count=1)
    if not count:
        return False
    path.write_text(stripped, encoding="utf-8")
    return True


def normalize_artifacts(paths: list[Path]) -> None:
    """对一组产物统一抹时间戳，并打印一行说明（不静默）。"""
    touched = [p.name for p in paths if p.is_file() and strip_sumo_timestamp(p)]
    if touched:
        print(f"[sumo] 已抹掉产物首行的生成时间戳（只改注释，内容未动）：{'、'.join(touched)}",
              file=sys.stdout)


def strip_local_paths(net_path: Path) -> bool:
    """删掉 `.net.xml` 里 `netconvert` 回显的 `<configuration>` 块。改动了返回 True。

    **为什么必须删**（两个理由，缺一都不行）：
      1. **那个块按「本机绝对路径」写了输入的 nod/edg/con 与输出路径** —— 产物**换台机器或换个
         目录就不一致**，"一键重建逐字节一致"根本立不住；
      2. 它把**本机目录泄进仓库** —— 仓库口径明写「本机具体目录不写入团队文档」。

    那个块只是**选项回显**，SUMO 运行时不读它。删掉**不影响任何路网内容**。
    """
    text = net_path.read_text(encoding="utf-8")
    stripped, count = _CONFIGURATION_BLOCK.subn("", text, count=1)
    if not count:
        return False
    net_path.write_text(stripped.rstrip() + "\n", encoding="utf-8")
    return True


def sanitize_net(net_path: Path) -> None:
    """`.net.xml` 的整体规整：**抹时间戳 + 删本机路径块**。不静默，逐条打印。"""
    if not net_path.is_file():
        return
    if strip_sumo_timestamp(net_path):
        print("[sumo] 已抹掉 net.xml 首行的生成时间戳（只改注释）")
    if strip_local_paths(net_path):
        print("[sumo] 已删掉 net.xml 里回显的 <netconvertConfiguration> 块"
              "（含本机绝对路径；只是选项回显，SUMO 运行时不读）")
